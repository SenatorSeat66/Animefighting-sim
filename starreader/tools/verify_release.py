#!/usr/bin/env python3
"""Verify a real signed StarReader ARM64 APK; emits machine-readable evidence.

Generated by CodeRabbit Coding Agent. Requires Android build-tools and JDK.
This inspects the artifact; it does not install or run it on a device.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import zipfile


def run(*args):
    return subprocess.check_output([str(x) for x in args], text=True, stderr=subprocess.STDOUT)


def require(condition, message):
    if not condition:
        raise SystemExit(message)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('apk', type=Path)
    parser.add_argument('--build-tools', type=Path, required=True)
    parser.add_argument('--version', default='0.2.0')
    parser.add_argument('--version-code', default='2')
    parser.add_argument('--certificate', help='Expected release signer SHA-256')
    args = parser.parse_args()
    signature = run(args.build_tools / 'apksigner', 'verify', '--verbose', '--print-certs', args.apk)
    require('Verified using v2 scheme (APK Signature Scheme v2): true' in signature,
            'APK does not have a valid v2 signature')
    certs = re.findall(r'Signer #\d+ certificate SHA-256 digest: ([0-9a-f]+)', signature)
    require(len(certs) == 1, 'Expected exactly one signer')
    require('CN=Android Debug' not in signature, 'Debug signing certificate is not a release key')
    if args.certificate:
        require(certs[0] == args.certificate.lower().replace(':', ''), 'Unexpected signing certificate')
    badging = run(args.build_tools / 'aapt2', 'dump', 'badging', args.apk)
    for expected in ["name='app.starreader.starreader'", f"versionCode='{args.version_code}'",
                     f"versionName='{args.version}'", "minSdkVersion:'24'", "targetSdkVersion:'36'",
                     "native-code: 'arm64-v8a'", "application-label:'StarReader'"]:
        require(expected in badging, f'Missing package metadata: {expected}')
    require('application-debuggable' not in badging, 'APK is debuggable')
    run(args.build_tools / 'zipalign', '-c', '-P', '16', '4', args.apk)
    libraries = {}
    with zipfile.ZipFile(args.apk) as archive:
        for name in archive.namelist():
            if not name.endswith('.so'):
                continue
            require(name.startswith('lib/arm64-v8a/'), f'Unexpected library ABI/location: {name}')
            data = archive.read(name)
            require(data[:6] == b'\x7fELF\x02\x01', f'Expected ELF64 little-endian: {name}')
            require(struct.unpack_from('<H', data, 18)[0] == 183, f'Not AArch64: {name}')
            offset = struct.unpack_from('<Q', data, 32)[0]
            size, count = struct.unpack_from('<HH', data, 54)
            alignments = []
            for index in range(count):
                header = struct.unpack_from('<IIQQQQQQ', data, offset + index * size)
                if header[0] == 1:
                    require(header[7] >= 16384, f'ELF alignment below 16 KiB: {name}')
                    require(header[2] % 16384 == header[3] % 16384,
                            f'ELF load offset is not 16 KiB congruent: {name}')
                    alignments.append(header[7])
            require(bool(alignments), f'No loadable ELF segments: {name}')
            libraries[name] = alignments
    require('lib/arm64-v8a/libquickjs.so' in libraries, 'QuickJS engine missing')
    with args.apk.open('rb') as file:
        digest = hashlib.file_digest(file, 'sha256').hexdigest()
    report = {
        'generated_by': 'CodeRabbit Coding Agent', 'artifact': args.apk.name,
        'package': 'app.starreader.starreader', 'version': args.version,
        'version_code': int(args.version_code), 'min_sdk': 24, 'target_sdk': 36,
        'abi': 'arm64-v8a', 'debuggable': False, 'signature_v2_verified': True,
        'certificate_sha256': certs[0], 'zip_alignment_16k_verified': True,
        'elf_load_segment_alignments': libraries, 'size_bytes': args.apk.stat().st_size,
        'sha256': digest,
        'device_install_launch_test': 'User-deferred; not performed by this script',
    }
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
